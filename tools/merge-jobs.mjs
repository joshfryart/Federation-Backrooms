// Registry builder for job modules: scans js/jobs/<billet>__<slug>.js, refuses id / title / file-name problems and fingerprint collisions
// (near-duplicate mechanics) between any two modules or with the old shared mechanics, then writes js/jobs/index.js (the job ids; modules load on demand by
// dynamic import, in the browser and in node alike). Run after merging a batch of authored modules:
//   node tools/merge-jobs.mjs            check + write js/jobs/index.js
//   node tools/merge-jobs.mjs --check    check only (exit 1 on a collision or when js/jobs/index.js is out of date)
// Full validation (auto-play etc.) of a batch is tools/check-jobs.mjs; this tool only needs the modules to import.
import { writeFileSync, readFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { listJobFiles, imp, nearDup, BASE, JOBDIR, catalogue } from './jobcheck-lib.mjs';

const files = listJobFiles(), mods = [], errs = [], cat = await catalogue(), K = await imp('js/jobs/kit.js');
for (const f of files) { try { const m = (await imp(f)).default; if (!m?.id || !m.fingerprint) { errs.push(`${basename(f)}: not a job module (define({...}) with a fingerprint)`); continue; } mods.push({ m, file: basename(f) }); } catch (e) { errs.push(`${basename(f)}: does not import: ${e.message}`); } }
const ids = new Map(), titles = new Map();
for (const { m, file } of mods) {
  const key = `${m.job.billet}|${m.job.label}|${m.job.type}`; if (!cat.jobs.has(key)) errs.push(`${file}: job ${key} is not in duties.json`);
  if (file !== K.fileFor(m.job.billet, m.job.label, m.job.type)) errs.push(`${file}: file name should be ${K.fileFor(m.job.billet, m.job.label, m.job.type)}`);
  if (ids.has(m.id)) errs.push(`${file}: same job as ${ids.get(m.id)}`); ids.set(m.id, file);
  if (titles.has(m.title)) errs.push(`${file}: title "${m.title}" also used by ${titles.get(m.title)}`); titles.set(m.title, file);
  for (const b of BASE) { const d = nearDup(m.fingerprint, b); if (d) errs.push(`${file}: near duplicate of the old mechanic ${b.id} (${d})`); }
}
for (let i = 0; i < mods.length; i++) for (let j = i + 1; j < mods.length; j++) { const d = nearDup(mods[i].m.fingerprint, mods[j].m.fingerprint); if (d) errs.push(`fingerprint collision: ${mods[i].file} vs ${mods[j].file} (${d})`); }
if (errs.length) { console.log('merge refused:\n  - ' + errs.join('\n  - ')); process.exit(1); }
// The registry holds only the ids: a module is fetched (dynamic import) the first time its billet's duty asks for it, so the 700 job files
// are not part of the page's static import graph. File names are derived from the job key (kit.js fileFor), as checked above.
const ID_LIST = mods.map(({ m }) => m.id).sort();
const src = `// GENERATED by tools/merge-jobs.mjs from js/jobs/*.js — do not edit by hand (docs/procedures.md). ${mods.length} job modules.
// Job modules load on demand (dynamic import), not with the page: js/main.js setupDuty asks for the player's own billet's jobs
// (loadModule per duty loop / mission task) and tests / tools ask for all of them (loadAll(duties)).
//   moduleFor(billet, label, type)   -> the loaded module or null (js/worksites.js jobFor falls back to the shared mechanics)
//   hasModule(billet, label, type)   -> true when a module exists for the job (loaded or not)
//   pendingFor(billet, label, type)  -> true when a module exists but has not arrived yet (js/main.js startJob waits rather than play the fallback)
//   loadModule(billet, label, type)  -> Promise<module | null>      loadAll(duties) -> Promise<MODULES> (every job of duties.json that has a module)
//   MODULES / JOBS                   the modules loaded so far (array in load-request order / by id)
import { jobId, fileFor } from './kit.js';
const IDS = new Set('${ID_LIST.join(',')}'.split(','));
export const MODULES = [], JOBS = {};
const PENDING = {};
const key = (billet, label, type) => (billet && label && type ? jobId(billet, label, type) : null);
export const moduleFor = (billet, label, type) => JOBS[key(billet, label, type)] || null;
export const hasModule = (billet, label, type) => IDS.has(key(billet, label, type));
export const pendingFor = (billet, label, type) => { const id = key(billet, label, type); return !!id && IDS.has(id) && !JOBS[id]; };
export function loadModule(billet, label, type) {
  const id = key(billet, label, type); if (!id || !IDS.has(id)) return Promise.resolve(null); if (JOBS[id]) return Promise.resolve(JOBS[id]);
  return PENDING[id] ||= import('./' + fileFor(billet, label, type)).then(m => { if (!JOBS[id]) { JOBS[id] = m.default; MODULES.push(m.default); } return JOBS[id]; },
    e => { delete PENDING[id]; console.warn('job module failed:', fileFor(billet, label, type), e?.message || e); return null; });
}
export async function loadAll(duties) {
  const all = [];
  for (const [b, d] of Object.entries(duties?.billets || {})) { for (const l of d.loops || []) all.push(loadModule(b, l.label, 'loop')); for (const [ms, ts] of Object.entries(d.tasks || {})) for (const t of ts) all.push(loadModule(b, t.task, 'task:' + ms)); }
  await Promise.all(all); return MODULES;
}
`;
const IDX = join(JOBDIR, 'index.js');
if (process.argv.includes('--check')) { let cur = ''; try { cur = readFileSync(IDX, 'utf8'); } catch { } if (cur !== src) { console.log('js/jobs/index.js is out of date: run node tools/merge-jobs.mjs'); process.exit(1); } }
else writeFileSync(IDX, src);
console.log(`${mods.length} job modules, no collisions${process.argv.includes('--check') ? '' : ' — wrote js/jobs/index.js'}`);
