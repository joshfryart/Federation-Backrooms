// Module preload hints for index.html:  node tools/build-preload.mjs [--check]
// Walks the static ES-module import graph from index.html's module scripts (import map: "three" and "three/addons/") and writes one
// <link rel="modulepreload"> per module between the PRELOAD markers in index.html, shallowest first. Without them the browser only learns
// of a module after fetching and parsing its importer: four round trips deep (main.js -> world.js -> propart*.js -> ...).
// Dynamic imports (js/jobs/<job>.js, ShaderPass in talk.js) are not listed: they load on demand.
//   --check   exit 1 when the block is out of date (CI), write nothing
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..'), HTML = join(ROOT, 'index.html');
const html = readFileSync(HTML, 'utf8');
const imap = JSON.parse(/<script type="importmap">([\s\S]*?)<\/script>/.exec(html)[1]).imports;
const resolve = (from, spec) => {
  if (imap[spec]) return normalize(imap[spec]);
  for (const k of Object.keys(imap)) if (k.endsWith('/') && spec.startsWith(k)) return normalize(imap[k] + spec.slice(k.length));
  return spec.startsWith('.') ? normalize(join(dirname(from), spec)) : null;
};
const STATIC = /(?:^|[;\n}])\s*(?:import|export)\s*(?:[\w*{}\s,$]+from\s*)?['"]([^'"]+)['"]/g;
const entries = [...html.matchAll(/<script type="module" src="([^"]+)"><\/script>/g)].map(m => normalize(m[1]));
const depth = new Map(), q = entries.map(e => [e, 0]);
while (q.length) {
  const [f, d] = q.shift(); if (depth.has(f) && depth.get(f) <= d) continue; depth.set(f, d);
  const p = join(ROOT, f); if (!existsSync(p)) throw new Error('missing module ' + f);
  const src = readFileSync(p, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of src.matchAll(STATIC)) { const r = resolve(f, m[1]); if (r) q.push([r, d + 1]); }
}
const list = [...depth].filter(([f]) => !entries.includes(f)).sort((a, b) => a[1] - b[1] || (a[0] < b[0] ? -1 : 1)).map(([f]) => f);
const START = '<!-- PRELOAD (generated by tools/build-preload.mjs: static module graph, shallowest first) -->', END = '<!-- /PRELOAD -->';
const block = `${START}\n${list.map(f => `<link rel="modulepreload" href="./${f}">`).join('\n')}\n${END}`;
const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
const out = re.test(html) ? html.replace(re, block) : html.replace(/(<script type="importmap">[\s\S]*?<\/script>\n)/, `$1${block}\n`);
if (process.argv.includes('--check')) { if (out !== html) { console.log('index.html module preload list is out of date: run node tools/build-preload.mjs'); process.exit(1); } console.log(`preload list up to date (${list.length} modules)`); }
else { writeFileSync(HTML, out); console.log(`index.html: ${list.length} modulepreload links, import depth ${Math.max(...depth.values())}`); }
